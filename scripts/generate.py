#!/usr/bin/env python3
"""Offline deterministic schema/dialect generation. --check verifies checked-in outputs."""
import argparse, json, pathlib, sys, subprocess, math, struct
ROOT = pathlib.Path(__file__).resolve().parents[1]
def outputs():
    schema = json.loads((ROOT / 'schema/parameters.json').read_text())
    rows = schema['parameters']
    count = len(rows)
    assert len({p['name'] for p in rows}) == count and all(len(p['name']) <= 16 for p in rows)
    def float_literal(v):
        v=float(v)
        for value,name in [(math.pi,'PI'),(math.tau,'TAU'),(math.pi/2,'FRAC_PI_2'),(math.pi/6,'FRAC_PI_6')]:
            if abs(abs(v)-value)<1e-9:return ('-' if v<0 else '')+'core::f32::consts::'+name
        packed=struct.pack('<f',v)
        for precision in range(1,10):
            text=format(v,'.%dg'%precision)
            if struct.pack('<f',float(text))==packed:break
        return text if '.' in text or 'e' in text else text+'.0'
    text = '// Generated by scripts/generate.py; edit schema/parameters.json.\n'
    text += 'pub const COUNT: usize = %d;\n' % count
    text += 'pub static PARAMETERS:[Parameter;COUNT]=[\n'
    for p in rows:
        text += 'Parameter{name:%s,default:%s,min:%s,max:%s,integer:%s,status:Status::%s},\n' % (json.dumps(p['name']),float_literal(p['default']),float_literal(p['minimum']),float_literal(p['maximum']),str(p['integer']).lower(),p['status'].capitalize())
    text += '];\n'
    text += 'pub const DEFAULT_VALUES:[f32;COUNT]=['+','.join(float_literal(p['default']) for p in rows)+'];\n'
    metadata = {'version': 1, 'parameters': [dict(name=p['name'], type='Float', default=p['default'], min=p['minimum'], max=p['maximum'], shortDesc=p['status'], rebootRequired=True) for p in rows]}
    dialect=json.loads((ROOT/'protocol/common-subset.json').read_text())
    wire='// Generated by scripts/generate.py; edit protocol/common-subset.json.\nfn dialect(id:u32)->Option<(u8,u8,u8)> { match id {\n'
    for key,value in dialect['messages'].items():
        wire += '    %s=>Some((%s)),\n' % (key,','.join(map(str,value)))
    wire+='    _=>None,\n}}\n'
    text=subprocess.run(['rustfmt','--edition','2024'],input=text,text=True,capture_output=True,check=True).stdout
    wire=subprocess.run(['rustfmt','--edition','2024'],input=wire,text=True,capture_output=True,check=True).stdout
    return {'crates/flight-config/src/schema.rs':text,'protocol/parameters.json':json.dumps(metadata,indent=2)+'\n','crates/flight-protocol/src/dialect.rs':wire}
def main():
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
    for name,text in outputs().items():
        path=ROOT/name
        if args.check:
            if not path.exists() or path.read_text()!=text:
                sys.exit('generated file differs: '+name)
        else:
            path.parent.mkdir(parents=True,exist_ok=True);path.write_text(text)
if __name__=='__main__':main()
