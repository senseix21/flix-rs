//! Wired enrollment is separate from ordinary radio command admission.
use crate::Owner;
use flight_core::Tick;
use flight_protocol::{
    Error,
    wire::{Packet, Policy, Signing},
};

pub struct RadioSession {
    policy: Option<Policy>,
    enrolled_at: u64,
    epoch: u64,
}
impl Default for RadioSession {
    fn default() -> Self {
        Self::EMPTY
    }
}
impl RadioSession {
    pub const EMPTY: Self = Self {
        policy: None,
        enrolled_at: 0,
        epoch: 0,
    };
    pub fn enabled(&self) -> bool {
        self.policy.is_some()
    }
    pub fn epoch(&self) -> u64 {
        self.epoch
    }
    /// Only a trusted wired caller may use this API. A fresh unpredictable key
    /// must be generated by the enrollment tool each time, including after reboot.
    /// Never route SETUP_SIGNING through a radio or proxy ingress.
    pub fn enroll(&mut self, packet: &Packet, owner: &mut Owner, now: Tick) -> Result<(), Error> {
        if packet.id != 256 || !owner.flight.stopped_maintenance() {
            return Err(Error::Unauthorized);
        }
        // Revocation precedes validation: interrupted/invalid rotation denies radio.
        self.policy = None;
        self.epoch = self.epoch.checked_add(1).ok_or(Error::Unauthorized)?;
        owner.discard_pending_authority();
        let p = &packet.payload;
        if p[8] != owner.settings.get("MAV_SYS_ID").unwrap_or(1.0) as u8 || p[9] != 1 {
            return Err(Error::Destination);
        }
        let key: [u8; 32] = p[10..42].try_into().map_err(|_| Error::Bounds)?;
        if key.iter().all(|v| *v == 0) {
            return Ok(());
        } // Explicit wired revoke.
        let timestamp = u64::from_le_bytes(p[..8].try_into().map_err(|_| Error::Bounds)?);
        self.policy = Some(Policy::Signed {
            system: packet.system,
            component: packet.component,
            signing: Signing::enrolled(key, timestamp, now.0)?,
        });
        self.enrolled_at = now.0;
        Ok(())
    }
    pub fn receive(&mut self, bytes: &[u8], owner: &mut Owner, now: Tick) -> bool {
        if now.0 < self.enrolled_at {
            self.policy = None;
            return false;
        }
        self.policy
            .as_mut()
            .is_some_and(|policy| owner.receive(bytes, policy, now))
    }
    pub fn sign(&mut self, bytes: &mut [u8], length: usize, now: Tick) -> Result<usize, Error> {
        let Some(Policy::Signed { signing, .. }) = &mut self.policy else {
            return Err(Error::Unauthorized);
        };
        signing.sign(bytes, length, now.0, 1)
    }
}
